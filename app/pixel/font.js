const ROWS = Object.fromEntries(Object.entries(G).map(([c, s]) => [c, s.split(' ')]));
export const ADV = 6, LINE = 9;
export const textWidth = (t) => t.length * ADV - 1;

export function text(g, t, x, y, color, shadow = '#050407') {
  t = t.toUpperCase();
  for (const pass of shadow ? [1, 0] : [0]) {
    g.fillStyle = pass ? shadow : color;
    let cx = x;
    for (const ch of t) {
      const R = ROWS[ch];
      if (R) for (let r = 0; r < 7; r++) for (let c = 0; c < 5; c++) if (R[r][c] === '#') g.fillRect(cx + c + pass * 0, y + r + pass, 1, 1);
      cx += ADV;
    }
  }
}
// greedy word wrap to a pixel width
export function wrap(t, w) {
  const out = []; let line = '';
  for (const word of t.split(' ')) {
    const next = line ? `${line} ${word}` : word;
    if (textWidth(next) > w && line) { out.push(line); line = word; } else line = next;
  }
  if (line) out.push(line);
  return out;
}
